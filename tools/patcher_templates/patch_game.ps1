# Veteran Upgrades: Patched Edition - game patcher for Windows (PowerShell 5.1+, built into Windows 10/11).
# Easiest: double-click "Install patch.bat", "Restore game.bat" or "Patch status.bat".
#   powershell -ExecutionPolicy Bypass -File patch_game.ps1 status|install|restore [-GameDir "<folder>"] [-Force]
# Changes a few hundred bytes of the game's empire.retail.dll so the mod can give abilities to one unit
# type at a time. Only patches the exact Steam build it knows (SHA-256), keeps the original as
# empire.retail.dll.vanilla, and refuses anything it doesn't recognise (e.g. after a Steam update) unless
# -Force. Single-player only: restore before playing multiplayer. Steam's "Verify integrity of game
# files" also undoes it. (Generated by tools/make_patchers.py - do not edit.)
param(
    [Parameter(Position = 0)][string]$Command = "status",
    [string]$GameDir = "",
    [switch]$Force
)
$ErrorActionPreference = "Stop"

$VanillaSha = "@VANILLA_SHA256@"
$PatchedSha = "@PATCHED_SHA256@"
$SignatureOffset = @SIGNATURE_OFFSET@
$Signature = "VU_ABILITY_PATCH "
$PatchVersion = "@PATCH_VERSION@"
$Edits = @(   # file offset, original bytes, patched bytes
@EDITS_PS@
)

function HexBytes([string]$hex) {
    $b = New-Object byte[] ($hex.Length / 2)
    for ($i = 0; $i -lt $b.Length; $i++) { $b[$i] = [Convert]::ToByte($hex.Substring($i * 2, 2), 16) }
    return ,$b
}

function Sha256File([string]$path) { return (Get-FileHash -Algorithm SHA256 -LiteralPath $path).Hash.ToLower() }

function Sha256Bytes([byte[]]$data) {
    $sha = [System.Security.Cryptography.SHA256]::Create()
    return ([BitConverter]::ToString($sha.ComputeHash($data)) -replace "-", "").ToLower()
}

function Find-Game {
    $roots = @()
    try { $roots += (Get-ItemProperty -Path "HKCU:\Software\Valve\Steam" -Name SteamPath -ErrorAction Stop).SteamPath } catch {}
    $roots += "C:\Program Files (x86)\Steam", "C:\Program Files\Steam"
    $libs = @()
    foreach ($r in $roots) {
        if (-not (Test-Path -LiteralPath $r)) { continue }
        $libs += $r
        $vdf = Join-Path $r "steamapps\libraryfolders.vdf"
        if (Test-Path -LiteralPath $vdf) {
            foreach ($m in [regex]::Matches((Get-Content -LiteralPath $vdf -Raw), '"path"\s+"([^"]+)"')) {
                $libs += $m.Groups[1].Value -replace '\\\\', '\'
            }
        }
    }
    foreach ($lib in $libs) {
        $game = Join-Path $lib "steamapps\common\Total War SHOGUN 2"
        if (Test-Path -LiteralPath (Join-Path $game "empire.retail.dll")) { return $game }
    }
    return $null
}

function Has-Signature([string]$dll) {
    $fs = [System.IO.File]::OpenRead($dll)
    try {
        if ($fs.Length -lt $SignatureOffset + $Signature.Length) { return $false }
        $fs.Position = $SignatureOffset
        $buf = New-Object byte[] $Signature.Length
        [void]$fs.Read($buf, 0, $buf.Length)
        return [System.Text.Encoding]::ASCII.GetString($buf) -eq $Signature
    } finally { $fs.Close() }
}

function Get-State([string]$dll) {
    $h = Sha256File $dll
    if ($h -eq $VanillaSha) { return "vanilla" }
    if ($h -eq $PatchedSha) { return "patched" }
    if (Has-Signature $dll) { return "patched by another version of this patcher" }
    return "unknown (not the Steam build this patcher knows - a Steam update?)"
}

function Do-Install([string]$dll) {
    $s = Get-State $dll
    if ($s -eq "patched") { Write-Host "Already patched."; return 0 }
    $backup = "$dll.vanilla"
    if ($s -eq "vanilla") { Copy-Item -LiteralPath $dll -Destination $backup -Force }
    elseif (-not ($s.StartsWith("patched by") -or $Force)) {
        Write-Host "Refusing: the game DLL is $s. Verify the game files in Steam first, or use -Force."; return 1
    }
    if (-not ((Test-Path -LiteralPath $backup) -and ((Sha256File $backup) -eq $VanillaSha))) {
        Write-Host "Refusing: no original backup. Verify the game files in Steam first."; return 1
    }
    $data = [System.IO.File]::ReadAllBytes($backup)
    foreach ($e in $Edits) {
        $off = [int64]$e[0]; $old = HexBytes $e[1]; $new = HexBytes $e[2]
        for ($i = 0; $i -lt $old.Length; $i++) {
            if ($data[$off + $i] -ne $old[$i]) { Write-Host ("Refusing: unexpected bytes at 0x{0:x}." -f $off); return 1 }
        }
        [Array]::Copy($new, 0, $data, $off, $new.Length)
    }
    if ((Sha256Bytes $data) -ne $PatchedSha) { Write-Host "Refusing: the result doesn't match the expected patched file."; return 1 }
    $tmp = "$dll.tmp"
    [System.IO.File]::WriteAllBytes($tmp, $data)
    Move-Item -LiteralPath $tmp -Destination $dll -Force
    Write-Host "Patched (patch version $PatchVersion). Original saved as empire.retail.dll.vanilla."
    Write-Host "Single-player only: restore the game before playing multiplayer."
    return 0
}

function Do-Restore([string]$dll) {
    $s = Get-State $dll
    if ($s -eq "vanilla") { Write-Host "The game is already original."; return 0 }
    if (-not ($s.StartsWith("patched") -or $Force)) {
        Write-Host "Refusing: the game DLL is $s, not patched by this patcher. Verify the game files in Steam instead."; return 1
    }
    $backup = "$dll.vanilla"
    if (-not ((Test-Path -LiteralPath $backup) -and ((Sha256File $backup) -eq $VanillaSha))) {
        Write-Host "No original backup found: use Steam's 'Verify integrity of game files' instead."; return 1
    }
    Copy-Item -LiteralPath $backup -Destination $dll -Force
    Write-Host "Restored the original game DLL."
    return 0
}

if (-not $GameDir) { $GameDir = Find-Game }
if (-not $GameDir -or -not (Test-Path -LiteralPath (Join-Path $GameDir "empire.retail.dll"))) {
    Write-Host 'Shogun 2 not found. Run again with -GameDir "<path to Total War SHOGUN 2>".'
    exit 1
}
$dll = Join-Path $GameDir "empire.retail.dll"
Write-Host "Game: $GameDir"
if (Get-Process -Name "Shogun2" -ErrorAction SilentlyContinue) {
    Write-Host "Shogun 2 is running: quit the game first."
    exit 1
}
switch ($Command) {
    "status"  { Write-Host ("Game DLL: " + (Get-State $dll)); exit 0 }
    "install" { exit (Do-Install $dll) }
    "restore" { exit (Do-Restore $dll) }
    default   { Write-Host "Usage: patch_game.ps1 status|install|restore [-GameDir <folder>] [-Force]"; exit 1 }
}
